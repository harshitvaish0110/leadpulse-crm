import { Brain, RefreshCw, AlertCircle } from 'lucide-react';
import Button from '../ui/Button';
import { Markdown } from '../../lib/markdown';
import { useAIStream } from '../../hooks/useAIStream';

/**
 * A streamed AI write-up (deal briefing, relationship summary): skeleton until
 * the first words arrive, then escape-first markdown as it streams. The footer
 * names the provider and offers Regenerate. Leaving the page cancels the request.
 */
export default function StreamingMarkdownCard({ title, subtitle, endpoint, body, emptyHint, actionLabel = 'Generate' }) {
  const { text, phase, error, provider, incomplete, start } = useAIStream();
  const generate = () => start(endpoint, body);
  const streaming = phase === 'streaming';

  return (
    <section aria-label={title} className="bg-gradient-to-br from-slate-800 to-slate-900 rounded-2xl p-5 text-white shadow-lg">
      <div className="flex items-center gap-2 mb-4">
        <div className="w-8 h-8 bg-indigo-500/20 rounded-lg flex items-center justify-center">
          <Brain size={16} className="text-indigo-300" />
        </div>
        <div>
          <h2 className="text-sm font-semibold text-white">{title}</h2>
          {subtitle && <p className="text-xs text-slate-400">{subtitle}</p>}
        </div>
      </div>

      {phase === 'idle' && (
        <div className="text-center py-3">
          {emptyHint && <p className="text-sm text-slate-400 mb-4">{emptyHint}</p>}
          <Button size="sm" className="w-full bg-indigo-600 hover:bg-indigo-700 border-0" onClick={generate}>
            <Brain size={14} className="mr-2" /> {actionLabel}
          </Button>
        </div>
      )}

      {streaming && !text && (
        <div className="space-y-2 animate-pulse" aria-label="Generating">
          {[1, 0.8, 0.9, 0.7, 0.85].map((w, i) => <div key={i} className="h-3 bg-white/10 rounded" style={{ width: `${w * 100}%` }} />)}
        </div>
      )}

      {text && (
        <div aria-live="polite" aria-busy={streaming}>
          <Markdown text={text} className="text-sm leading-relaxed text-slate-300 [&_h3]:text-white [&_h4]:text-slate-100 [&_strong]:text-white" />
        </div>
      )}

      {phase === 'error' && (
        <div role="alert" className="flex items-start gap-2 bg-red-500/10 border border-red-500/20 rounded-xl p-3 mt-3">
          <AlertCircle size={14} className="text-red-400 flex-shrink-0 mt-0.5" />
          <p className="text-xs text-red-300">{incomplete ? `The answer stopped early: ${error}` : error}</p>
        </div>
      )}

      {(phase === 'done' || phase === 'error') && (
        <div className="flex items-center justify-between mt-4 pt-3 border-t border-white/10">
          <span className="text-[11px] text-slate-500">{provider ? `Generated by ${provider}` : ''}</span>
          <button type="button" onClick={generate} className="flex items-center gap-1.5 text-xs text-slate-300 hover:text-white">
            <RefreshCw size={12} /> {phase === 'error' ? 'Try again' : 'Regenerate'}
          </button>
        </div>
      )}
    </section>
  );
}
